/**
 * Unit tests for coverageSelection.js — pure-logic only (no jsdom, no React render).
 *
 * Mirror of src/lib/groupHierarchy.test.js pattern: import from vitest, no
 * react/testing-library imports. localStorage is stubbed with a Map-backed fake
 * because this suite runs in plain node, matching the rest of src/lib.
 *
 * What this guards: the Landing page's Alpha Communities rail opens on a state.
 * Which state is a precedence question with four inputs, and getting the order
 * wrong is silent — the panel still renders, just on the wrong state. These tests
 * pin the order and, just as importantly, pin that every candidate is validated
 * against live coverage before it is trusted.
 */

import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import {
  resolveInitialCoverageState,
  getLastCoverageState,
  setLastCoverageState,
  homeStateFromAddress,
  LAST_COVERAGE_STATE_KEY,
} from './coverageSelection.js';

const COVERED = ['CA', 'IN', 'ME', 'MD', 'MA', 'TX', 'UT'];

describe('resolveInitialCoverageState — precedence', () => {
  it('prefers the deep-linked state over everything else', () => {
    // An uncovered-area search bounces the user here with ?coverage_state=TX and
    // scrolls them to it. That intent is for this visit only, but while it lasts
    // it outranks whatever they browsed last time.
    expect(resolveInitialCoverageState({
      deepLinkState: 'TX',
      rememberedState: 'CA',
      homeState: 'ME',
      coveredAbbrevs: COVERED,
    })).toBe('TX');
  });

  it('accepts a lowercase deep-link param', () => {
    // coverage_state arrives from a URL, so its case is not ours to assume.
    expect(resolveInitialCoverageState({
      deepLinkState: 'tx',
      coveredAbbrevs: COVERED,
    })).toBe('TX');
  });

  it('falls through to the remembered state when the deep link is not covered', () => {
    // A hand-edited or stale URL must not blank the panel.
    expect(resolveInitialCoverageState({
      deepLinkState: 'WY',
      rememberedState: 'CA',
      homeState: 'ME',
      coveredAbbrevs: COVERED,
    })).toBe('CA');
  });

  it('prefers the remembered state over the home state', () => {
    // "Let's remember where they were" — an explicit browse beats an inferred home.
    expect(resolveInitialCoverageState({
      rememberedState: 'UT',
      homeState: 'CA',
      coveredAbbrevs: COVERED,
    })).toBe('UT');
  });

  it('falls through to the home state when the remembered state is no longer covered', () => {
    // Coverage is regenerated by scripts/gen-coverage.mjs. A state can leave the
    // list between visits, and a stale localStorage value must not select a ghost.
    expect(resolveInitialCoverageState({
      rememberedState: 'WY',
      homeState: 'MA',
      coveredAbbrevs: COVERED,
    })).toBe('MA');
  });

  it('uses the home state when nothing has been browsed yet', () => {
    // First visit, signed in, home location in a state we cover.
    expect(resolveInitialCoverageState({
      homeState: 'me',
      coveredAbbrevs: COVERED,
    })).toBe('ME');
  });

  it('selects nothing when the home state is not covered', () => {
    // The whole point of dropping the hardcoded California default: guessing wrong
    // is worse than showing a prompt.
    expect(resolveInitialCoverageState({
      homeState: 'WY',
      coveredAbbrevs: COVERED,
    })).toBeNull();
  });

  it('selects nothing on a cold first visit', () => {
    expect(resolveInitialCoverageState({ coveredAbbrevs: COVERED })).toBeNull();
  });

  it('selects nothing when coverage is empty', () => {
    expect(resolveInitialCoverageState({
      deepLinkState: 'CA',
      rememberedState: 'CA',
      homeState: 'CA',
      coveredAbbrevs: [],
    })).toBeNull();
  });
});

describe('homeStateFromAddress', () => {
  // CompassContext exposes the signed-in user's home location as a formatted
  // address string, and already parses the state out of it with this same
  // "two caps before a ZIP" shape. Landing needs the abbrev, not the string.

  it('reads the state out of a formatted US address', () => {
    expect(homeStateFromAddress('123 Main St, Portland, OR 97201, USA')).toBe('OR');
  });

  it('reads the state from a ZIP+4 address', () => {
    expect(homeStateFromAddress('500 Elm Ave, Austin, TX 78701-2210, USA')).toBe('TX');
  });

  it('is not fooled by an earlier two-letter token', () => {
    // "ST" in a street name precedes no ZIP, so it must not win over "MA".
    expect(homeStateFromAddress('9 ST JAMES AVE, Boston, MA 02116')).toBe('MA');
  });

  it('returns null for an address with no state/ZIP pair', () => {
    expect(homeStateFromAddress('Somewhere, Canada')).toBeNull();
  });

  it('returns null when there is no address at all', () => {
    expect(homeStateFromAddress(null)).toBeNull();
    expect(homeStateFromAddress('')).toBeNull();
  });
});

describe('last-browsed-state storage', () => {
  let store;
  const realLocalStorage = globalThis.localStorage;

  beforeEach(() => {
    store = new Map();
    globalThis.localStorage = {
      getItem: (k) => (store.has(k) ? store.get(k) : null),
      setItem: (k, v) => store.set(k, String(v)),
      removeItem: (k) => store.delete(k),
    };
  });

  afterEach(() => {
    globalThis.localStorage = realLocalStorage;
  });

  it('round-trips the state the user last browsed', () => {
    setLastCoverageState('TX');
    expect(getLastCoverageState()).toBe('TX');
  });

  it('normalizes to uppercase on write', () => {
    setLastCoverageState('tx');
    expect(store.get(LAST_COVERAGE_STATE_KEY)).toBe('TX');
  });

  it('returns null when nothing has been stored', () => {
    expect(getLastCoverageState()).toBeNull();
  });

  it('clears the key when given a falsy state', () => {
    setLastCoverageState('TX');
    setLastCoverageState(null);
    expect(store.has(LAST_COVERAGE_STATE_KEY)).toBe(false);
  });

  it('returns null instead of throwing when storage is blocked', () => {
    // Safari private browsing and hardened profiles throw on access rather than
    // returning null. locationPref.js already swallows this; so must we, or the
    // whole section fails to render for those users.
    globalThis.localStorage = {
      getItem() { throw new Error('SecurityError'); },
      setItem() { throw new Error('SecurityError'); },
      removeItem() { throw new Error('SecurityError'); },
    };
    expect(getLastCoverageState()).toBeNull();
    expect(() => setLastCoverageState('TX')).not.toThrow();
  });
});
